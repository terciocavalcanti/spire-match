export async function seedProperties(db: Database): Promise<void> {
  for (const seed of PROPERTY_SEEDS) {
    const [property] = await db
      .insert(properties)
      .values({
        slug: seed.slug,
        title: seed.title,
        description: seed.description,
        type: seed.type,
        purpose: seed.purpose,
        status: seed.status,
        price: seed.price.toFixed(2),
        condominiumFee: seed.condominiumFee?.toFixed(2) ?? null,
        iptu: seed.iptu?.toFixed(2) ?? null,
        areaSqm: seed.areaSqm.toFixed(2),
        bedrooms: seed.bedrooms,
        bathrooms: seed.bathrooms,
        parkingSpaces: seed.parkingSpaces,
        neighborhood: seed.neighborhood,
        city: seed.city,
        state: seed.state,
        lat: seed.lat,
        lng: seed.lng,
        coverImageUrl: `https://picsum.photos/seed/${seed.imageSeeds[0]}/1200/800`,
        features: seed.features,
        acceptedPaymentMethods: seed.acceptedPaymentMethods,
        isExclusive: seed.isExclusive,
        exclusiveType: seed.exclusiveType,
        isSponsored: seed.isSponsored,
      })
      .onConflictDoUpdate({
        target: properties.slug,
        set: {
          title: seed.title,
          description: seed.description,
          status: seed.status,
          price: seed.price.toFixed(2),
          updatedAt: new Date(),
        },
      })
      .returning({ id: properties.id });

    if (!property) continue;

    await db.delete(propertyImages).where(eq(propertyImages.propertyId, property.id));
    await db.insert(propertyImages).values(
      seed.imageSeeds.map((imageSeed, index) => ({
        propertyId: property.id,
        url: `https://picsum.photos/seed/${imageSeed}/1200/800`,
        alt: `${seed.title} — foto ${index + 1} (demonstração)`,
        position: index,
      })),
    );

    const [existingPrice] = await db
      .select({ price: propertyPriceHistory.price })
      .from(propertyPriceHistory)
      .where(eq(propertyPriceHistory.propertyId, property.id))
      .limit(1);
    if (!existingPrice) {
      await db.insert(propertyPriceHistory).values({ propertyId: property.id, price: seed.price.toFixed(2) });
    }
  }
   
  console.log(`Imóveis DEMONSTRAÇÃO garantidos: ${PROPERTY_SEEDS.length}`);
}
